import { describe, expect, it } from "vitest";
import { highlight, type Token } from "./highlight";

const kinds = (line: Token[]) => line.filter((t) => t.kind).map((t) => [t.kind, t.text]);

describe("highlight", () => {
  it("marks python keywords, strings, numbers, comments and decorators", () => {
    const [deco, def, body] = highlight(
      '@pytest.mark.bug("BUG-1")\ndef test_01_cart(page: Page) -> None:\n    expect(x).to_have_count(3)  # three rows',
      "python",
    );
    expect(kinds(deco)).toEqual([
      ["d", "@pytest.mark.bug"],
      ["s", '"BUG-1"'],
    ]);
    expect(kinds(def)).toEqual([
      ["k", "def"],
      ["k", "None"],
    ]);
    expect(kinds(body)).toEqual([
      ["n", "3"],
      ["c", "# three rows"],
    ]);
  });

  it("carries python docstrings across lines", () => {
    const lines = highlight('"""Generated by QAPilot.\n\nRun: pytest\n"""\nimport re', "python");
    expect(lines[0]).toEqual([{ kind: "s", text: '"""Generated by QAPilot.' }]);
    expect(lines[2]).toEqual([{ kind: "s", text: "Run: pytest" }]);
    expect(lines[3]).toEqual([{ kind: "s", text: '"""' }]);
    expect(kinds(lines[4])).toEqual([["k", "import"]]);
  });

  it("handles escaped quotes and f-strings", () => {
    const [line] = highlight('x = f"say \\"hi\\"" + name', "python");
    expect(kinds(line)).toEqual([["s", 'f"say \\"hi\\""']]);
  });

  it("highlights typescript, including block comments and template strings", () => {
    const lines = highlight('/**\n * Suite\n */\ntest("cart", async ({ page }) => {\n  await page.goto(`${BASE}/cart`); // go\n});', "typescript");
    expect(lines[1]).toEqual([{ kind: "c", text: " * Suite" }]);
    expect(kinds(lines[3])).toEqual([
      ["s", '"cart"'],
      ["k", "async"],
    ]);
    expect(kinds(lines[4])).toEqual([
      ["k", "await"],
      ["s", "`${BASE}/cart`"],
      ["c", "// go"],
    ]);
  });

  it("does not treat identifiers ending in a quote prefix letter as string prefixes", () => {
    const [line] = highlight("buffer = 'abc'", "python");
    expect(kinds(line)).toEqual([["s", "'abc'"]]);
    expect(line[0]).toEqual({ kind: null, text: "buffer = " });
  });
});
