PYTEST_INI = """\
[pytest]
markers =
    bug(id): the QAPilot bug report this test reproduces
"""

PLAYWRIGHT_CONFIG = """\
import { defineConfig, devices } from '@playwright/test';

export default defineConfig({
  testDir: '.',
  testMatch: '*.spec.ts',
  reporter: [['list'], ['html', { open: 'never' }]],
  use: { trace: 'retain-on-failure', video: 'retain-on-failure' },
  projects: [{ name: 'chromium', use: { ...devices['Desktop Chrome'] } }],
});
"""

README = """\
# QAPilot regression suite

Generated from run `{run_id}` against {target}.

| File | Runner |
| --- | --- |
| `{py}` | `pip install pytest-playwright && playwright install chromium`, then `pytest {py}` |
| `{ts}` | `npm i -D @playwright/test && npx playwright install chromium`, then `npx playwright test` |

Both files contain the same scenarios. Set `BASE_URL` to run them against another build
(default: `{base}`). Tests linked to a bug are expected to fail until it is fixed.
"""


def write_suite(recorder: Recorder, run_dir: Path, run_id: str, story: str) -> dict[str, Any]:
    tests_dir = run_dir / "tests"
    tests_dir.mkdir(parents=True, exist_ok=True)
    python_src = render_python(recorder, run_id, story)
    compile(python_src, PY_FILE, "exec")  # fail loudly here rather than inside pytest
    (tests_dir / PY_FILE).write_text(python_src, encoding="utf-8")
    (tests_dir / TS_FILE).write_text(render_typescript(recorder, run_id), encoding="utf-8")
    (tests_dir / "pytest.ini").write_text(PYTEST_INI, encoding="utf-8")
    (tests_dir / "playwright.config.ts").write_text(PLAYWRIGHT_CONFIG, encoding="utf-8")
    base = app_base(recorder.target_url)
    (tests_dir / "README.md").write_text(
        README.format(run_id=run_id, target=recorder.target_url, py=PY_FILE, ts=TS_FILE, base=base), encoding="utf-8"
    )
    tests = plan_tests(recorder)
    manifest = {
        "base_url": base,
        "python": f"tests/{PY_FILE}",
        "typescript": f"tests/{TS_FILE}",
        "tests": [t.__dict__ for t in tests],
    }
    (tests_dir / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return manifest
