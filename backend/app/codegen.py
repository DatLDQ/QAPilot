"""Turn the recorded session into a Playwright regression suite (Python and TypeScript).

Each scenario becomes one test that replays the agent's steps with the locators it
verified during the run. Checks are soft assertions of the *correct* behaviour, so a
test fails for as long as its bug exists and passes once it is fixed. URLs are written
relative to ``BASE_URL``, which lets the same suite run against another build.
"""

import json
import re
import unicodedata
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from urllib.parse import urlparse

from .locators import py_str, render_py, render_ts, ts_str
from .recorder import Bug, Recorder, Scenario, Step

PY_FILE = "test_qapilot.py"
TS_FILE = "qapilot.spec.ts"


@dataclass
class GeneratedTest:
    scenario_id: int
    name: str  # pytest function name
    title: str  # TypeScript title
    expected_outcome: str
    bug_ids: list[str]


def app_base(target_url: str) -> str:
    """The URL the suite's relative paths hang off: the target without query/fragment, as a directory."""
    parsed = urlparse(target_url)
    path = parsed.path or "/"
    if not path.endswith("/"):
        last = path.rsplit("/", 1)[-1]
        path = path.rsplit("/", 1)[0] + "/" if "." in last else path + "/"
    return f"{parsed.scheme}://{parsed.netloc}{path}"


def relative_url(url: str, base: str) -> str:
    if url.startswith(base):
        return url[len(base):]
    if url == base.rstrip("/"):
        return ""
    target, root = urlparse(url), urlparse(base)
    if (target.scheme, target.netloc) == (root.scheme, root.netloc):
        return url[len(f"{target.scheme}://{target.netloc}"):]  # absolute path on the same host
    return url


def slugify(name: str, limit: int = 60) -> str:
    # "đ" has no decomposition, so map it by hand before dropping the remaining accents.
    name = name.replace("đ", "d").replace("Đ", "D")
    ascii_name = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()
    slug = re.sub(r"[^a-z0-9]+", "_", ascii_name.lower()).strip("_")
    if len(slug) > limit:
        # Cut at a word boundary when there is one reasonably close to the limit.
        cut = slug.rfind("_", 0, limit + 1)
        slug = slug[:cut] if cut >= limit // 2 else slug[:limit]
    return slug.rstrip("_") or "scenario"


def _one_line(text: str) -> str:
    return " ".join(str(text).split())


def _doc_safe(text: str) -> str:
    return _one_line(text).replace("\\", "/").replace('"""', "'''")


def _scenario_bugs(scenario: Scenario, bugs: list[Bug]) -> list[Bug]:
    ids = {b for s in scenario.steps for b in s.bug_ids}
    return [b for b in bugs if b.id in ids or b.scenario_id == scenario.id]


def plan_tests(recorder: Recorder) -> list[GeneratedTest]:
    tests = []
    for scenario in recorder.scenarios:
        if not scenario.steps:
            continue
        bugs = _scenario_bugs(scenario, recorder.bugs)
        tests.append(GeneratedTest(
            scenario_id=scenario.id,
            name=f"test_{scenario.id:02d}_{slugify(scenario.name)}",
            title=f"{scenario.id:02d} · {scenario.name}",
            expected_outcome=scenario.expected_outcome,
            bug_ids=[b.id for b in bugs],
        ))
    return tests


# --- Python -----------------------------------------------------------------------

_PY_EXPECT = {
    "visible": "to_be_visible()",
    "hidden": "to_be_hidden()",
    "checked": "to_be_checked()",
    "unchecked": "not_to_be_checked()",
    "enabled": "to_be_enabled()",
    "disabled": "to_be_disabled()",
}
_PY_EXPECT_VALUE = {
    "text_equals": "to_have_text",
    "text_contains": "to_contain_text",
    "value_equals": "to_have_value",
}

_PY_HEADER = '''\
"""Regression tests generated by QAPilot from an exploratory session.

Run:     {run_id}
Target:  {target}
Story:   {story}

Every check asserts the correct, expected behaviour. Tests linked to a bug fail until
that bug is fixed. Point the suite at another build with the BASE_URL variable:

    BASE_URL={base} pytest {file}
"""

import os
import re
from collections.abc import Callable
from urllib.parse import urljoin

import pytest
from playwright.sync_api import Page, expect

BASE_URL = os.environ.get("BASE_URL", {base_literal})
expect.set_options(timeout=5_000)


def url(path: str = "") -> str:
    return urljoin(BASE_URL, path)


class SoftAssertions:
    """Collects failed checks so one run reports every broken expectation, not just the first."""

    def __init__(self) -> None:
        self.failures: list[str] = []

    def check(self, label: str, assertion: Callable[[], None]) -> None:
        try:
            assertion()
        except AssertionError as exc:
            detail = next((line.strip() for line in str(exc).splitlines() if line.strip()), "failed")
            self.failures.append(f"{{label}}: {{detail}}")

    def assert_all(self) -> None:
        if self.failures:
            raise AssertionError(f"{{len(self.failures)}} check(s) failed:\\n- " + "\\n- ".join(self.failures))


def assert_no_errors(errors: list[str]) -> None:
    assert not errors, "Console errors: " + " | ".join(errors[:3])


@pytest.fixture(autouse=True)
def accept_dialogs(page: Page) -> None:
    page.on("dialog", lambda dialog: dialog.accept())


@pytest.fixture
def soft() -> SoftAssertions:
    return SoftAssertions()
'''


def _py_check(step: Step) -> str:
    label = py_str(step.description)
    expected = step.expected or ""
    if step.assertion == "no_console_errors":
        return f"soft.check({label}, lambda: assert_no_errors(errors))"
    if step.assertion == "url_contains":
        body = f"expect(page).to_have_url(re.compile(re.escape({py_str(expected)})))"
    elif step.assertion == "title_contains":
        body = f"expect(page).to_have_title(re.compile(re.escape({py_str(expected)})))"
    else:
        loc = render_py(step.locator or [])
        if step.assertion in _PY_EXPECT:
            body = f"expect({loc}).{_PY_EXPECT[step.assertion]}"
        elif step.assertion == "count_equals":
            body = f"expect({loc}).to_have_count({int(expected)})"
        else:
            body = f"expect({loc}).{_PY_EXPECT_VALUE[step.assertion or '']}({py_str(expected)})"
    return f"soft.check({label}, lambda: {body})"


def _py_step(step: Step, base: str) -> str:
    loc = render_py(step.locator) if step.locator else None
    match step.kind:
        case "goto":
            return f"page.goto(url({py_str(relative_url(str(step.value), base))}))"
        case "click":
            return f"{loc}.click()"
        case "fill":
            return f"{loc}.fill({py_str(str(step.value))})"
        case "select":
            return f"{loc}.select_option(label={py_str(str(step.value))})"
        case "check":
            return f"{loc}.set_checked({bool(step.value)})"
        case "press":
            key = py_str(str(step.value))
            return f"{loc}.press({key})" if loc else f"page.keyboard.press({key})"
        case "hover":
            return f"{loc}.hover()"
        case "expect":
            return _py_check(step)
    raise ValueError(f"Unknown step kind {step.kind}")


def _uses_console(scenario: Scenario) -> bool:
    return any(s.assertion == "no_console_errors" for s in scenario.steps)


def render_python(recorder: Recorder, run_id: str, story: str) -> str:
    base = app_base(recorder.target_url)
    out = [_PY_HEADER.format(
        run_id=run_id, target=_doc_safe(recorder.target_url), story=_doc_safe(story)[:200], base=base,
        base_literal=py_str(base), file=PY_FILE,
    )]
    by_id = {s.id: s for s in recorder.scenarios}
    bugs = {b.id: b for b in recorder.bugs}
    for test in plan_tests(recorder):
        scenario = by_id[test.scenario_id]
        out.append("")
        out.append("")
        for bug_id in test.bug_ids:
            out.append(f"@pytest.mark.bug({py_str(bug_id)})")
        out.append(f"def {test.name}(page: Page, soft: SoftAssertions) -> None:")
        doc = [scenario.name]
        if test.bug_ids:
            doc.append("")
            doc += [f"Known bug {b}: {bugs[b].title}" for b in test.bug_ids if b in bugs]
        body = "\n".join(f"    {_doc_safe(d)}".rstrip() for d in doc).lstrip()
        out.append(f'    """{body}' + ('\n    """' if len(doc) > 1 else '"""'))
        if _uses_console(scenario):
            out.append("    errors: list[str] = []")
            out.append('    page.on("console", lambda msg: errors.append(msg.text) if msg.type == "error" else None)')
            out.append('    page.on("pageerror", lambda exc: errors.append(f"Uncaught {exc.name}: {exc.message}"))')
        start = relative_url(scenario.start_url or recorder.target_url, base)
        out.append(f"    page.goto(url({py_str(start)}))")
        for step in scenario.steps:
            note = f"  [{', '.join(step.bug_ids)}]" if step.bug_ids else ""
            out.append(f"    # {_one_line(step.description)}{note}".rstrip())
            out.append(f"    {_py_step(step, base)}")
        out.append("    soft.assert_all()")
    return "\n".join(out) + "\n"


# --- TypeScript -------------------------------------------------------------------

_TS_EXPECT = {
    "visible": "toBeVisible()",
    "hidden": "toBeHidden()",
    "checked": "toBeChecked()",
    "unchecked": "not.toBeChecked()",
    "enabled": "toBeEnabled()",
    "disabled": "toBeDisabled()",
}
_TS_EXPECT_VALUE = {"text_equals": "toHaveText", "text_contains": "toContainText", "value_equals": "toHaveValue"}

_TS_HEADER = """\
/**
 * Regression tests generated by QAPilot from an exploratory session.
 *
 * Run:     {run_id}
 * Target:  {target}
 *
 * Every check asserts the correct, expected behaviour. Tests annotated with a bug fail
 * until that bug is fixed. Point the suite at another build with BASE_URL:
 *
 *   BASE_URL={base} npx playwright test
 */
import {{ expect, test }} from '@playwright/test';

const BASE_URL = process.env.BASE_URL ?? {base_literal};
const url = (path = '') => new URL(path, BASE_URL).toString();
const escapeRe = (s: string) => s.replace(/[.*+?^${{}}()|[\\]\\\\]/g, '\\\\$&');

test.beforeEach(async ({{ page }}) => {{
  page.on('dialog', (dialog) => dialog.accept());
}});
"""


def _ts_check(step: Step) -> str:
    label = ts_str(step.description)
    expected = step.expected or ""
    if step.assertion == "no_console_errors":
        return f"expect.soft(consoleErrors, {label}).toEqual([]);"
    if step.assertion in ("url_contains", "title_contains"):
        matcher = "toHaveURL" if step.assertion == "url_contains" else "toHaveTitle"
        return f"await expect.soft(page, {label}).{matcher}(new RegExp(escapeRe({ts_str(expected)})));"
    loc = render_ts(step.locator or [])
    if step.assertion in _TS_EXPECT:
        return f"await expect.soft({loc}, {label}).{_TS_EXPECT[step.assertion]};"
    if step.assertion == "count_equals":
        return f"await expect.soft({loc}, {label}).toHaveCount({int(expected)});"
    return f"await expect.soft({loc}, {label}).{_TS_EXPECT_VALUE[step.assertion or '']}({ts_str(expected)});"


def _ts_step(step: Step, base: str) -> str:
    loc = render_ts(step.locator) if step.locator else None
    match step.kind:
        case "goto":
            return f"await page.goto(url({ts_str(relative_url(str(step.value), base))}));"
        case "click":
            return f"await {loc}.click();"
        case "fill":
            return f"await {loc}.fill({ts_str(str(step.value))});"
        case "select":
            return f"await {loc}.selectOption({{ label: {ts_str(str(step.value))} }});"
        case "check":
            return f"await {loc}.setChecked({'true' if step.value else 'false'});"
        case "press":
            if loc:
                return f"await {loc}.press({ts_str(str(step.value))});"
            return f"await page.keyboard.press({ts_str(str(step.value))});"
        case "hover":
            return f"await {loc}.hover();"
        case "expect":
            return _ts_check(step)
    raise ValueError(f"Unknown step kind {step.kind}")


def render_typescript(recorder: Recorder, run_id: str) -> str:
    base = app_base(recorder.target_url)
    out = [_TS_HEADER.format(run_id=run_id, target=recorder.target_url, base=base, base_literal=ts_str(base))]
    by_id = {s.id: s for s in recorder.scenarios}
    bugs = {b.id: b for b in recorder.bugs}
    for test in plan_tests(recorder):
        scenario = by_id[test.scenario_id]
        out.append("")
        details = ""
        if test.bug_ids:
            notes = ", ".join(
                f"{{ type: 'bug', description: {ts_str(f'{b}: {bugs[b].title}')} }}" for b in test.bug_ids if b in bugs
            )
            details = f"{{ annotation: [{notes}] }}, "
        out.append(f"test({ts_str(test.title)}, {details}async ({{ page }}) => {{")
        if _uses_console(scenario):
            out.append("  const consoleErrors: string[] = [];")
            out.append(
                "  page.on('console', (msg) => { if (msg.type() === 'error') consoleErrors.push(msg.text()); });"
            )
            out.append("  page.on('pageerror', (err) => consoleErrors.push(`Uncaught ${err.name}: ${err.message}`));")
        start = relative_url(scenario.start_url or recorder.target_url, base)
        out.append(f"  await page.goto(url({ts_str(start)}));")
        for step in scenario.steps:
            note = f"  [{', '.join(step.bug_ids)}]" if step.bug_ids else ""
            out.append(f"  // {_one_line(step.description)}{note}".rstrip())
            out.append(f"  {_ts_step(step, base)}")
        out.append("});")
    return "\n".join(out) + "\n"


